local core = require("typetrainer.core")

describe("core.chars", function()
  it("splits ascii", function()
    eq({ "a", "b", "c" }, core.chars("abc"))
  end)
  it("keeps multibyte characters whole", function()
    eq({ "ü", "€", "😀", "x" }, core.chars("ü€😀x"))
  end)
  it("handles the empty string", function()
    eq({}, core.chars(""))
  end)
  it("never drops bytes on invalid input", function()
    eq("\128a\194", table.concat(core.chars("\128a\194")))
  end)
  it("counts characters", function()
    eq(3, core.char_count("a€b"))
  end)
end)

describe("core.diff_line", function()
  it("reports nothing for a correct prefix", function()
    local ranges, wrong, typed = core.diff_line("hel", "hello")
    eq({}, ranges)
    eq(0, wrong)
    eq(3, typed)
  end)
  it("marks a single wrong character", function()
    eq({ { 1, 2 } }, (core.diff_line("hxllo", "hello")))
  end)
  it("merges adjacent wrong characters", function()
    local ranges, wrong = core.diff_line("hXXlo", "hello")
    eq({ { 1, 3 } }, ranges)
    eq(2, wrong)
  end)
  it("keeps separate ranges apart", function()
    eq({ { 0, 1 }, { 2, 3 } }, (core.diff_line("XeXlo", "hello")))
  end)
  it("marks characters typed past the end of the target", function()
    local ranges, wrong = core.diff_line("hi!!", "hi")
    eq({ { 2, 4 } }, ranges)
    eq(2, wrong)
  end)
  it("marks everything when the target line is empty", function()
    eq({ { 0, 3 } }, (core.diff_line("abc", "")))
  end)
  it("uses byte offsets for multibyte text", function()
    -- "ü" is 2 bytes, so the wrong "x" sits at byte 2
    eq({ { 2, 3 } }, (core.diff_line("üx", "üy")))
    eq({ { 0, 2 } }, (core.diff_line("ü", "u")))
  end)
  it("accepts a correct multibyte character", function()
    eq({}, (core.diff_line("café", "café!")))
  end)
end)

describe("core.ghost", function()
  it("returns the whole target when nothing is typed", function()
    eq("hello", core.ghost("", "hello"))
  end)
  it("returns the remainder", function()
    eq("lo", core.ghost("hel", "hello"))
  end)
  it("counts a wrong character as typed", function()
    eq("llo", core.ghost("hx", "hello"))
  end)
  it("is empty when the line is complete or over-typed", function()
    eq("", core.ghost("hello", "hello"))
    eq("", core.ghost("hello!!", "hello"))
  end)
  it("counts characters, not bytes", function()
    eq("fé", core.ghost("ca", "café"))
    eq("é", core.ghost("caf", "café"))
  end)
end)

describe("core.expand_tabs", function()
  it("leaves text without tabs alone", function()
    eq("abc", core.expand_tabs("abc", 3, 8))
  end)
  it("expands a leading tab to the next stop", function()
    eq("        x", core.expand_tabs("\tx", 0, 8))
  end)
  it("accounts for the starting column", function()
    eq("     x", core.expand_tabs("\tx", 3, 8))
  end)
  it("expands consecutive tabs", function()
    eq("    ab  c", core.expand_tabs("\tab\tc", 0, 4))
  end)
end)

describe("core.compare", function()
  local target = { "ab", "cd", "ef" }

  it("shows the full target as ghost for an empty buffer", function()
    local r = core.compare({ "" }, target)
    eq("ab", r.lines[1].ghost)
    eq({ "cd", "ef" }, r.remaining)
    eq(0, r.typed)
  end)
  it("tracks progress across lines", function()
    local r = core.compare({ "ab", "c" }, target)
    eq("", r.lines[1].ghost)
    eq("d", r.lines[2].ghost)
    eq({ "ef" }, r.remaining)
    eq(3, r.typed)
    eq(0, r.wrong)
  end)
  it("counts wrong characters", function()
    local r = core.compare({ "ax", "cd" }, target)
    eq({ { 1, 2 } }, r.lines[1].wrong)
    eq(1, r.wrong)
  end)
  it("marks lines beyond the target as wrong", function()
    local r = core.compare({ "ab", "cd", "ef", "gh" }, target)
    eq({ { 0, 2 } }, r.lines[4].wrong)
    eq("", r.lines[4].ghost)
    eq({}, r.remaining)
  end)
  it("caps the number of remaining lines", function()
    local r = core.compare({ "" }, { "a", "b", "c", "d" }, 2)
    eq({ "b", "c" }, r.remaining)
  end)
end)

describe("core.is_complete", function()
  it("is true only for an exact match", function()
    eq(true, core.is_complete({ "a", "b" }, { "a", "b" }))
    eq(false, core.is_complete({ "a" }, { "a", "b" }))
    eq(false, core.is_complete({ "a", "b", "" }, { "a", "b" }))
    eq(false, core.is_complete({ "a", "x" }, { "a", "b" }))
  end)
end)

describe("core.total_chars", function()
  it("sums characters over all lines", function()
    eq(5, core.total_chars({ "ab", "c€d" }))
  end)
end)

describe("core.normalize_lines / load", function()
  it("strips carriage returns", function()
    eq({ "a", "b" }, core.normalize_lines({ "a\r", "b" }))
  end)
  it("rejects empty input", function()
    local lines, err = core.normalize_lines({})
    eq(nil, lines)
    eq("target is empty", err)
  end)
  it("loads a file", function()
    eq({ "x", "", "y" }, core.load(tmpfile({ "x", "", "y" })))
  end)
  it("reports a missing file", function()
    local lines, err = core.load("/nonexistent/file.txt")
    eq(nil, lines)
    eq("cannot read file: /nonexistent/file.txt", err)
  end)
  it("reports an empty file", function()
    local lines, err = core.load(tmpfile({}))
    eq(nil, lines)
    assert(err:find("target is empty"), err)
  end)
end)
