local config = require("typetrainer.config")

local function fails(opts, pattern)
  local ok, err = pcall(config.normalize, opts)
  eq(false, ok)
  assert(tostring(err):find(pattern, 1, true), "error was: " .. tostring(err))
end

describe("config.normalize", function()
  it("returns defaults", function()
    local cfg = config.normalize()
    eq({ "auto" }, cfg.indicator)
    eq("current", cfg.open)
  end)
  it("does not modify the defaults", function()
    config.normalize({ open = "tab", indicator = { "color" } })
    eq("current", config.defaults.open)
    eq("auto", config.defaults.indicator)
  end)
  it("accepts a list of indicators", function()
    eq({ "color", "underline" }, config.normalize({ indicator = { "color", "underline" } }).indicator)
  end)
  it("rejects bad values", function()
    fails({ indicator = "bold" }, "invalid indicator 'bold'")
    fails({ indicator = {} }, "must not be empty")
    fails({ open = "float" }, "invalid open")
    fails({ error_color = 1 }, "error_color")
    fails({ indicator = { "auto", "color" } }, "cannot be combined")
  end)
  it("rejects unknown options, including the removed mode", function()
    fails({ colour = "red" }, "unknown option 'colour'")
    fails({ mode = "normal" }, "unknown option 'mode'")
  end)
end)

describe("config.highlight_attrs", function()
  it("underlines with the error color", function()
    eq({ underline = true, sp = "#f00" }, config.highlight_attrs({ "underline" }, "#f00"))
    -- the underline defaults to the red text color on terminals without colored underlines
  end)
  it("colors the text", function()
    eq({ fg = "#f00", ctermfg = "Red" }, config.highlight_attrs({ "color" }, "#f00"))
  end)
  it("sets the background", function()
    eq({ bg = "#f00", ctermbg = "Red" }, config.highlight_attrs({ "background" }, "#f00"))
  end)
  it("combines indicators", function()
    eq(
      { underline = true, sp = "#f00", fg = "#f00", ctermfg = "Red" },
      config.highlight_attrs({ "underline", "color" }, "#f00")
    )
  end)
  it("keeps text readable when color and background combine", function()
    eq(
      { bg = "#f00", ctermbg = "Red", fg = "white", ctermfg = "White" },
      config.highlight_attrs({ "color", "background" }, "#f00")
    )
  end)
end)

describe("config.is_plain", function()
  it("treats prose and unknown types as plain", function()
    eq(true, config.is_plain(nil))
    eq(true, config.is_plain("text"))
    eq(true, config.is_plain("markdown"))
  end)
  it("treats programming languages as code", function()
    eq(false, config.is_plain("lua"))
    eq(false, config.is_plain("python"))
  end)
end)

describe("config.resolve_indicator", function()
  it("leaves explicit indicators alone", function()
    eq({ "color" }, config.resolve_indicator({ "color" }, { termguicolors = true, plain = false }))
  end)
  it("auto: red underline with termguicolors", function()
    eq({ "underline" }, config.resolve_indicator({ "auto" }, { termguicolors = true, plain = true }))
    eq({ "underline" }, config.resolve_indicator({ "auto" }, { termguicolors = true, plain = false }))
  end)
  it("auto: red text for plain text without termguicolors", function()
    eq({ "color" }, config.resolve_indicator({ "auto" }, { termguicolors = false, plain = true }))
  end)
  it("auto: red background for code without termguicolors", function()
    eq({ "background" }, config.resolve_indicator({ "auto" }, { termguicolors = false, plain = false }))
  end)
end)

describe("config.parse_args", function()
  it("takes a path", function()
    local path, opts = config.parse_args({ "a.txt" })
    eq("a.txt", path)
    eq({}, opts)
  end)
  it("parses options in any position", function()
    local path, opts = config.parse_args({ "open=vsplit", "a.txt", "indicator=underline,color" })
    eq("a.txt", path)
    eq({ indicator = { "underline", "color" }, open = "vsplit" }, opts)
  end)
  it("fails without exactly one path", function()
    local path, err = config.parse_args({ "open=tab" })
    eq(nil, path)
    assert(err:find("usage"), err)
    eq(nil, (config.parse_args({ "a", "b" })))
  end)
end)
